// Parses references/laws-of-power.pdf (the supplied companion reference) into data/laws.js.
// Usage: node tools/build-laws.mjs   (requires `pdftotext` from poppler-utils)
import { execFileSync } from 'node:child_process';
import { writeFileSync, existsSync, readFileSync } from 'node:fs';

const PDF = 'references/laws-of-power.pdf';
if (!existsSync(PDF)) { console.error(`Missing ${PDF}`); process.exit(1); }
const raw = execFileSync('pdftotext', ['-layout', PDF, '-'], { encoding: 'utf8' });
const lines = raw.split('\n')
  .map(l => l.trim())
  .filter(l => l && !/^Original concise companion/.test(l) && !/^48 LAWS OF POWER — CLAUDE REFERENCE/.test(l));

const FIELDS = [
  ['Core principle:', 'principle'], ['Useful when / failure mode:', 'risk'], ['Psychology / power dynamic:', 'psychology'],
  ['Practical application:', 'application'], ['Defensive reading:', 'defense'], ['Game scenario seed:', 'seed'], ['Suggested mechanic tags:', 'tags'],
];
const laws = [];
let cur = null, field = null;
for (const line of lines) {
  const m = line.match(/^LAW (\d\d) — (.+)$/);
  if (m) { cur = { n: Number(m[1]), title: m[2], titleOpen: true }; laws.push(cur); field = null; continue; }
  if (!cur) continue;
  if (/^3\. Cross-law relationships/.test(line)) break;
  const f = FIELDS.find(([p]) => line.startsWith(p));
  if (f) { field = f[1]; cur.titleOpen = false; cur[field] = line.slice(f[0].length).trim(); continue; }
  if (cur.titleOpen) { cur.title += ' ' + line; continue; }
  if (field) cur[field] += ' ' + line;
}
if (laws.length !== 48) { console.error(`Expected 48 laws, parsed ${laws.length}`); process.exit(1); }

const CLUSTERS = {
  'Reputation and visibility': [1, 4, 5, 6, 25, 30, 34, 37, 46],
  'Information and uncertainty': [3, 4, 14, 18, 21, 33, 39, 44],
  'Trust and alliances': [2, 12, 13, 20, 24, 27, 43],
  'Timing and restraint': [8, 16, 22, 28, 29, 35, 36, 47, 48],
  'Power concentration and resistance': [7, 11, 15, 17, 19, 23, 31, 41, 42, 45],
  'Ethical risk and defensive reading': [10, 12, 14, 15, 17, 26, 27, 33, 39, 40, 44],
};
// tools/simple/laws.json holds the plain-English version shown in the game. The PDF text is kept under `ref`.
const SIMPLE = JSON.parse(readFileSync('tools/simple/laws.json', 'utf8'));
const out = laws.map(l => ({
  n: l.n, id: `law${l.n}`, title: l.title.replace(/\s+/g, ' ').trim(),
  clusters: Object.entries(CLUSTERS).filter(([, ns]) => ns.includes(l.n)).map(([k]) => k),
  tags: (l.tags || '').replace(/\.$/, '').split(/[,;]\s*/).map(s => s.trim().toLowerCase()).filter(Boolean),
  plain: SIMPLE[l.n].plain,
  principle: SIMPLE[l.n].principle, risk: SIMPLE[l.n].risk, application: SIMPLE[l.n].application, defense: SIMPLE[l.n].defense,
  ref: { principle: l.principle, risk: l.risk, psychology: l.psychology, application: l.application, defense: l.defense, seed: l.seed },
  // Titles come from the supplied companion reference. They have not been compared to the original book.
  verified: false,
}));
const file = `// GENERATED by tools/build-laws.mjs from references/laws-of-power.pdf. Do not edit by hand; re-run the script.
// Source: the supplied companion reference (original concise summaries), NOT the book itself. Plain-English text from tools/simple/laws.json is shown in the game; the reference text is kept under ref. Titles are therefore
// marked verified:false until compared against the original book (see tools/verify-laws.mjs).

export const LAWS_SOURCE = {
  verified: false,
  note: 'Law titles and summaries come from the supplied companion reference PDF and have not been checked against the original book.',
};

export const LAWS = ${JSON.stringify(out, null, 2)};

export const LAW_BY_ID = Object.fromEntries(LAWS.map(l => [l.id, l]));
export const lawId = n => \`law\${n}\`;
`;
writeFileSync('data/laws.js', file);
console.log(`Wrote data/laws.js with ${out.length} laws.`);
